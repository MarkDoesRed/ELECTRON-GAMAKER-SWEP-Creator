document.addEventListener('DOMContentLoaded', () => {
    const inputs = document.querySelectorAll('input, select');
    const codeOutput = document.getElementById('lua-output');
    const typeSelect = document.getElementById('wep-type');
    const hitscanSettings = document.getElementById('hitscan-settings');
    const projSettings = document.getElementById('projectile-settings');
    const propSettings = document.getElementById('prop-settings');
    typeSelect.addEventListener('change', () => {
        hitscanSettings.classList.add('hidden');
        projSettings.classList.add('hidden');
        propSettings.classList.add('hidden');
        if (typeSelect.value === 'hitscan') hitscanSettings.classList.remove('hidden');
        if (typeSelect.value === 'projectile') projSettings.classList.remove('hidden');
        if (typeSelect.value === 'prop') propSettings.classList.remove('hidden');
        
        generateLua();
    });
    function generateLua() {
        const name = document.getElementById('wep-name').value;
        const category = document.getElementById('wep-category').value;
        const vmodel = document.getElementById('wep-vmodel').value;
        const wmodel = document.getElementById('wep-wmodel').value;
        const ammo = document.getElementById('wep-ammo').value;
        const clip = document.getElementById('wep-clip').value;
        const delay = document.getElementById('wep-delay').value;
        const isAuto = document.getElementById('wep-auto').checked;
        const wepType = typeSelect.value;
        const damage = document.getElementById('wep-damage').value;
        const projEnt = document.getElementById('wep-projectile-ent').value;
        const propMdl = document.getElementById('wep-prop-mdl').value;
        const holdType = document.getElementById('wep-holdtype').value;
        const shootSound = document.getElementById('wep-sound').value;
        const recoil = document.getElementById('wep-recoil').value;
        const spread = document.getElementById('wep-spread').value;
        const useHands = (vmodel.includes('/c_') || vmodel.includes('\\c_')) ? 'true' : 'false';
        let luaCode = `AddCSLuaFile()
-- Custom Weapon Generated by GMWMaker
SWEP.PrintName = "${name}"
SWEP.Category = "${category}"
SWEP.Spawnable = true
SWEP.AdminOnly = false

SWEP.Base = "weapon_base"

SWEP.ViewModel = "${vmodel}"
SWEP.WorldModel = "${wmodel}"
SWEP.UseHands = ${useHands}

SWEP.Primary.ClipSize = ${clip}
SWEP.Primary.DefaultClip = ${clip * 3}
SWEP.Primary.Automatic = ${isAuto ? 'true' : 'false'}
SWEP.Primary.Ammo = "${ammo}"
SWEP.Primary.Delay = ${delay}

SWEP.Secondary.ClipSize = -1
SWEP.Secondary.DefaultClip = -1
SWEP.Secondary.Automatic = false
SWEP.Secondary.Ammo = "none"

function SWEP:Initialize()
    self:SetHoldType("${holdType}")
end

function SWEP:PrimaryAttack()
    if not self:CanPrimaryAttack() then return end

    local ply = self:GetOwner()
    if not IsValid(ply) then return end

    self:EmitSound("${shootSound}")
    self:TakePrimaryAmmo(1)
    self:SetNextPrimaryFire(CurTime() + self.Primary.Delay)
    
    self:ShootEffects()

    ply:ViewPunch(Angle(-${recoil}, math.Rand(-1, 1), 0))
`;

        if (wepType === 'hitscan') {
            luaCode += `
    self:ShootBullet(${damage}, 1, ${spread})
end`;
        } else {
            luaCode += `
    if SERVER then
        local ent = ents.Create("${wepType === 'prop' ? 'prop_physics' : projEnt}")
        if IsValid(ent) then
            ${wepType === 'prop' ? `ent:SetModel("${propMdl}")` : ''}
            local spawnPos = ply:GetShootPos() + ply:GetAimVector() * 32
            ent:SetPos(spawnPos)
            ent:SetAngles(ply:EyeAngles())
            ent:SetOwner(ply)
            ent:Spawn()
            ent:Activate()
            
            local phys = ent:GetPhysicsObject()
            if IsValid(phys) then
                phys:Wake()
                local aimDir = ply:GetAimVector()
                aimDir = aimDir + VectorRand() * (${spread} / 2)
                phys:SetVelocity(aimDir * 2000)
            end
        end
    end
end`;
        }

        codeOutput.value = luaCode;
    }

    inputs.forEach(input => {
        input.addEventListener('input', generateLua);
        input.addEventListener('change', generateLua);
    });

    generateLua();
    const exportBtn = document.getElementById('export-btn');
    exportBtn.addEventListener('click', async () => {
        if (!window.electronAPI) return alert("Electron IPC Bridge not found!");
        
        const currentCode = document.getElementById('lua-output').value;
        const addonName = document.getElementById('addon-folder').value.replace(/[^a-z0-9_]/gi, '_').toLowerCase(); 
        const className = document.getElementById('wep-class').value.replace(/[^a-z0-9_]/gi, '_').toLowerCase();
        
        const success = await window.electronAPI.exportAddon(currentCode, addonName, className);
        
        if (success) {
            exportBtn.innerText = "Addon Generated Successfully!";
            exportBtn.style.backgroundColor = "#44bd32";
            setTimeout(() => {
                exportBtn.innerText = "Generate Addon Folder";
                exportBtn.style.backgroundColor = "";
            }, 3000);
        }
    });

    const browseBtns = document.querySelectorAll('.browse-btn');
    
    if (browseBtns[0]) {
        browseBtns[0].addEventListener('click', async () => {
            if (!window.electronAPI) return;
            const path = await window.electronAPI.openFileDialog();
            if (path) { document.getElementById('wep-vmodel').value = path; generateLua(); }
        });
    }
    
    if (browseBtns[1]) {
        browseBtns[1].addEventListener('click', async () => {
            if (!window.electronAPI) return;
            const path = await window.electronAPI.openFileDialog();
            if (path) { document.getElementById('wep-wmodel').value = path; generateLua(); }
        });
    }
    
    if (browseBtns[2]) {
        browseBtns[2].addEventListener('click', async () => {
            if (!window.electronAPI) return;
            const path = await window.electronAPI.openFileDialog();
            if (path) { document.getElementById('wep-prop-mdl').value = path; generateLua(); }
        });
    }
    const ytLink = document.getElementById('yt-link');
    if (ytLink) {
        ytLink.addEventListener('click', (e) => {
            e.preventDefault();
            window.electronAPI.openExternal('https://www.youtube.com/@MNCEOfficial'); 
        });
    }
});